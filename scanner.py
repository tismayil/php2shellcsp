def _connect(host, port, tls=False, timeout=10):
    raw = socket.create_connection((host, port), timeout=timeout)
    if tls:
        ctx = ssl.create_default_context()
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        return ctx.wrap_socket(raw, server_hostname=host)
    return raw


def _dechunk(body):
    out = bytearray()
    while body:
        idx = body.find(b"\r\n")
        if idx < 0:
            break
        try:
            size = int(body[:idx].split(b";")[0], 16)
        except ValueError:
            return bytes(body)
        if size == 0:
            break
        out += body[idx + 2:idx + 2 + size]
        body = body[idx + 2 + size + 2:]
    return bytes(out)


def _read_response(sock, max_resp=262144):
    buf = bytearray()
    try:
        while len(buf) < max_resp:
            chunk = sock.recv(65536)
            if not chunk:
                break
            buf += chunk
    except (socket.timeout, ssl.SSLError, OSError):
        pass
    return bytes(buf)


def _parse(raw):
    head, _, body = raw.partition(b"\r\n\r\n")
    lines = head.split(b"\r\n")
    status = 0
    headers = {}
    if lines and lines[0].startswith(b"HTTP/"):
        parts = lines[0].split(b" ")
        if len(parts) > 1 and parts[1].isdigit():
            status = int(parts[1])
    for line in lines[1:]:
        if b":" not in line:
            continue
        name, _, value = line.partition(b":")
        key = name.decode("latin-1").strip().lower()
        val = value.decode("latin-1").strip()
        headers[key] = (headers[key] + ", " + val) if key in headers else val
    if "chunked" in headers.get("transfer-encoding", "").lower():
        body = _dechunk(body)
    return status, headers, body


def http_req(host, port, method, path, tls=False, headers=None, body=None,
             timeout=10, max_resp=262144):
    hdrs = {"Host": host, "Connection": "close", "User-Agent": UA,
            "Accept": "*/*", "Accept-Encoding": "identity"}
    if headers:
        hdrs.update(headers)
    if body is not None:
        hdrs["Content-Length"] = str(len(body))
    req = f"{method} {path} HTTP/1.1\r\n"
    req += "".join(f"{k}: {v}\r\n" for k, v in hdrs.items())
    req += "\r\n"
    try:
        sock = _connect(host, port, tls=tls, timeout=timeout)
    except (socket.timeout, OSError, ssl.SSLError) as exc:
        return {"status": 0, "headers": {}, "body": b"", "truncated": False, "error": str(exc)}
    try:
        sock.sendall(req.encode("latin-1") + (body or b""))
        raw = _read_response(sock, max_resp=max_resp)
    except (socket.timeout, OSError, ssl.SSLError) as exc:
        return {"status": 0, "headers": {}, "body": b"", "truncated": False, "error": str(exc)}
    finally:
        try:
            sock.close()
        except OSError:
            pass
    if not raw:
        return {"status": 0, "headers": {}, "body": b"", "truncated": False,
                "error": "empty response"}
    status, headers, payload = _parse(raw)
    return {"status": status, "headers": headers, "body": payload[:max_resp],
            "truncated": len(payload) >= max_resp, "error": None}


def follow(host, port, tls, path, timeout=10, max_hops=3):
    cur = (host, port, tls, path)
    chain = []
    resp = None
    for _ in range(max_hops + 1):
        resp = http_req(cur[0], cur[1], "GET", cur[3], tls=cur[2], timeout=timeout)
        if resp["error"] or resp["status"] not in (301, 302, 303, 307, 308):
            break
        loc = resp["headers"].get("location", "")
        if not loc:
            break
        chain.append(loc)
        n = urlparse(loc)
        if n.hostname:
            ntls = n.scheme == "https"
            npath = (n.path or "/") + (("?" + n.query) if n.query else "")
            cur = (n.hostname, n.port or (443 if ntls else 80), ntls, npath)
        else:
            npath = loc if loc.startswith("/") else "/" + loc
            cur = (cur[0], cur[1], cur[2], npath.split("#")[0])
    return {"host": cur[0], "port": cur[1], "tls": cur[2], "path": cur[3],
            "resp": resp, "redirects": chain}


def parse_target(url):
    if "://" not in url:
        url = "https://" + url
    n = urlparse(url)
    tls = n.scheme == "https"
    host = n.hostname or ""
    port = n.port or (443 if tls else 80)
    path = (n.path or "/") + (("?" + n.query) if n.query else "")
    return host, port, tls, path


def mp_body(boundary, parts):
    out = bytearray()
    for name, data, filename in parts:
        out += b"--" + boundary + b"\r\n"
        disp = f'Content-Disposition: form-data; name="{name}"'
        if filename is not None:
            disp += f'; filename="{filename}"'
            out += disp.encode("latin-1") + b"\r\nContent-Type: text/plain\r\n\r\n"
        else:
            out += disp.encode("latin-1") + b"\r\n\r\n"
        out += data + b"\r\n"
    out += b"--" + boundary + b"--\r\n"
    return bytes(out)


def is_vuln_version(v):
    if v is None or v < VULN_FLOOR:
        return None
    br = f"{v[0]}.{v[1]}"
    if br in PATCHED:
        return v < PATCHED[br]
    if br in EOL_BRANCHES:
        return True
    return None


def detect_waf(resp, baseline, method="POST"):
    if not resp or resp.get("error"):
        return {"blocked": False, "vendor": None, "status": None, "evidence": "no response"}
    status = resp.get("status") or 0
    headers = resp.get("headers") or {}
    body = (resp.get("body") or b"")[:32768].decode("utf-8", "replace").lower()
    hits = []
    vendor = None
    for name, keys in WAF_HEADERS.items():
        for key in keys:
            if key in headers:
                hits.append(f"header:{key}")
                vendor = vendor or name
    for name, needles in WAF_BODY.items():
        for needle in needles:
            if needle in body:
                hits.append(f"body:{needle}")
                vendor = vendor or name
    srv = headers.get("server", "").lower()
    if srv in ("cloudflare", "ddos-guard", "sucuri/cloudproxy", "barracuda"):
        hits.append(f"server:{srv}")
        vendor = vendor or ("cloudflare" if "cloudflare" in srv else srv)
    challengy = bool(headers.get("cf-mitigated")) or "challenges.cloudflare.com" in body
    blocked = False
    if status in BLOCK_CODES:
        if hits or challengy:
            blocked = True
        elif baseline and baseline.get("status") == 200 and method == "POST":
            blocked = True
            vendor = vendor or "generic"
            hits.append(f"GET 200 / POST {status}")
        elif status == 403:
            blocked = True
            vendor = vendor or "generic"
            hits.append("status:403")
    elif status in (200, 301, 302) and challengy:
        blocked = True
        hits.append("challenge-body")
    return {"blocked": blocked, "vendor": vendor or ("generic" if blocked else None),
            "status": status, "evidence": ", ".join(dict.fromkeys(hits))[:200] or "-",
            "challenge": challengy}


class Spinner:
    FRAMES = "⠋⠙⠹⠸⠼⠴⠦⠧⠇⠏"

    def __init__(self, ui, label):
        self.ui = ui
        self.label = label
        self.detail = ""
        self._stop = threading.Event()
        self._thread = None
        self._i = 0
        self._t0 = time.time()

    def __enter__(self):
        if self.ui.anim and self.ui.tty:
            self._thread = threading.Thread(target=self._run, daemon=True)
            self._thread.start()
        return self

    def _run(self):
        while not self._stop.is_set():
            frame = self.FRAMES[self._i % len(self.FRAMES)]
            self._i += 1
            txt = self.ui.paint(f"  {frame} {self.label}…", Palette.CYA)
            if self.detail:
                txt += self.ui.paint(f"  {self.detail}", Palette.GRY)
            txt += self.ui.paint(f"  {time.time() - self._t0:4.1f}s", Palette.DIM)
            sys.stdout.write("\r\033[K" + txt)
            sys.stdout.flush()
            time.sleep(0.08)

    def __exit__(self, *exc):
        self._stop.set()
        if self._thread:
            self._thread.join(timeout=1)
            sys.stdout.write("\r\033[K")
            line = self.ui.paint("  ✔ ", Palette.GRN, Palette.BOLD)
            line += self.ui.paint(self.label, Palette.WHT)
            if self.detail:
                line += self.ui.paint("  " + self.detail, Palette.GRY)
            sys.stdout.write(line + "\n")
            sys.stdout.flush()


